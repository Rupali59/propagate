#!/usr/bin/env node
/**
 * Vendor a SUBSET of Lucide's icon data into widget/propagate-queue.jsx.
 *
 * WHY A SCRIPT, AND WHY A GENERATED BLOCK (decision E8/D9, 2026-10-15).
 * The widget cannot `import` an icon package: Übersicht resolves no relative
 * import for a symlinked widget, and the marketplace install runs no
 * `npm install`, so node_modules cannot be assumed. `lucide` is therefore NOT a
 * dependency (it is not in package.json and must not be added). Its node data —
 * `[["path", {d: ...}], ...]` per icon, React-free, ISC — is copied into one
 * marked block in the widget instead.
 *
 * THE ICON LIST IS DERIVED, NOT CURATED (rule:derive-dont-curate). It is read
 * from the widget's own text — every `icon="x"` and `icon: 'x'` outside the
 * vendored block — so using a new icon and forgetting to vendor it is a red
 * test (tests/unit/widget-icons.test.mjs), never a missing glyph on a desktop
 * that has no console to say so.
 *
 * A PINNED COPY NOTHING CHECKS IS THE DRIFT THIS PROJECT EXISTS TO DETECT, so
 * the block header records package, version, license, the icon list and a
 * sha256 of the block BODY (every line after the `sha256:` line, up to the end
 * marker, joined with "\n", no trailing newline). The test recomputes it.
 *
 * USAGE
 *   node scripts/vendor-lucide-icons.mjs            fetch lucide@PIN with `npm pack`
 *                                                   into a temp dir and rewrite the block
 *   node scripts/vendor-lucide-icons.mjs --source <dir>   use an already-extracted
 *                                                   package (the dir holding package.json)
 *   node scripts/vendor-lucide-icons.mjs --check    re-derive and compare; exit 1 on drift,
 *                                                   writes nothing
 */
import { readFileSync, writeFileSync, mkdtempSync, existsSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import path from "node:path";
import vm from "node:vm";

export const PKG = "lucide";
export const VERSION = "1.55.0";
export const LICENSE = "ISC";
export const BEGIN = "// ---- vendored:lucide begin ----";
export const END = "// ---- vendored:lucide end ----";

const ROOT = path.join(import.meta.dirname, "..");
const WIDGET = path.join(ROOT, "widget/propagate-queue.jsx");

/** The widget's text with the vendored block removed, so its own keys never count as references. */
export function outsideBlock(src) {
  const i = src.indexOf(BEGIN);
  const j = src.indexOf(END);
  if (i === -1 || j === -1 || j < i) throw new Error(`widget has no ${BEGIN} ... ${END} block`);
  return src.slice(0, i) + src.slice(j + END.length);
}

/** Every icon name the widget references: `icon="x"` and `icon: 'x'`. */
export function referencedIcons(src) {
  const names = new Set();
  for (const m of outsideBlock(src).matchAll(/\bicon(?:=|:\s*)["']([a-z][a-z0-9-]*)["']/g)) names.add(m[1]);
  return [...names].sort();
}

export function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

/** Parse one lucide esm icon file: `const Name = [ ... ];` */
function parseIcon(file) {
  const text = readFileSync(file, "utf8");
  const m = /const \w+ = (\[[\s\S]*?\]);\s*\n\s*export/.exec(text);
  if (!m) throw new Error(`could not read the node array out of ${file}`);
  return vm.runInNewContext(`(${m[1]})`);
}

export function buildBlock(names, pkgDir) {
  const meta = JSON.parse(readFileSync(path.join(pkgDir, "package.json"), "utf8"));
  if (meta.name !== PKG || meta.version !== VERSION || meta.license !== LICENSE) {
    throw new Error(`source is ${meta.name}@${meta.version} (${meta.license}); this script pins ${PKG}@${VERSION} (${LICENSE})`);
  }
  if (names.length < 5) throw new Error(`only ${names.length} icon references found in the widget — the scan has gone blind`);
  const lines = ["const LUCIDE_ICONS = {"];
  names.forEach((n, i) => {
    const file = path.join(pkgDir, "dist/esm/icons", `${n}.mjs`);
    if (!existsSync(file)) throw new Error(`the widget references icon "${n}", which ${PKG}@${VERSION} does not have`);
    lines.push(`  ${JSON.stringify(n)}: ${JSON.stringify(parseIcon(file))}${i < names.length - 1 ? "," : ""}`);
  });
  lines.push("};");
  const body = lines.join("\n");
  const head = [
    BEGIN,
    `// VENDORED — ${PKG} ${VERSION} (${LICENSE}), https://lucide.dev. Generated by scripts/vendor-lucide-icons.mjs; do not edit by hand.`,
    `// package: ${PKG}`,
    `// version: ${VERSION}`,
    `// license: ${LICENSE}`,
    `// icons: ${names.join(", ")}`,
    `// sha256: ${sha256(body)}`,
  ];
  return [...head, body, END].join("\n");
}

function fetchPackage() {
  const dir = mkdtempSync(path.join(tmpdir(), "lucide-"));
  execFileSync("npm", ["pack", `${PKG}@${VERSION}`, "--pack-destination", dir, "--silent"], { cwd: dir, stdio: ["ignore", "pipe", "inherit"] });
  execFileSync("tar", ["-xzf", path.join(dir, `${PKG}-${VERSION}.tgz`), "-C", dir]);
  return { dir: path.join(dir, "package"), cleanup: () => rmSync(dir, { recursive: true, force: true }) };
}

function main() {
  const argv = process.argv.slice(2);
  const check = argv.includes("--check");
  const si = argv.indexOf("--source");
  let source = null;
  let cleanup = () => {};
  if (si !== -1) {
    source = path.resolve(argv[si + 1] ?? "");
  } else {
    ({ dir: source, cleanup } = fetchPackage());
  }
  try {
    const src = readFileSync(WIDGET, "utf8");
    const block = buildBlock(referencedIcons(src), source);
    const i = src.indexOf(BEGIN);
    const j = src.indexOf(END) + END.length;
    const next = src.slice(0, i) + block + src.slice(j);
    if (check) {
      if (next !== src) {
        console.error("widget's vendored lucide block differs from a fresh derivation — run without --check");
        process.exit(1);
      }
      console.log(`ok: vendored block matches ${PKG}@${VERSION}`);
      return;
    }
    writeFileSync(WIDGET, next);
    console.log(`wrote ${referencedIcons(src).length} icons from ${PKG}@${VERSION} into ${WIDGET}`);
  } finally {
    cleanup();
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) main();
